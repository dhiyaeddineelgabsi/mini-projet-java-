public class Nom {
    private int id;
    private String nom;
    private String nomComplet;

    public Nom(int id, String nom, String nomComplet) {
        this.id = id;
        this.nom = nom;
        this.nomComplet = nomComplet;
    }

    public int getId() {
        return id;
    }

    public String getNom() {
        return nom;
    }

    public String getNomComplet() {
        return nomComplet;
    }




}